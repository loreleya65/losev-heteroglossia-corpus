# --------------------------------------------------------------------------- #
# 1. Процедура отделена от поиска латиницы: под «OOV через pymorphy3»
#    объединять кириллицу и латиницу нельзя.
# 2. Критерий OOV уточнён: кандидатом считается словоформа, у которой НИ ОДИН
#    разбор не является словарным (all(not p.is_known)). Проверка «слова нет в
#    словаре» без обращения к is_known даёт ложные срабатывания на омонимии.
# 3. Отсекается служебная часть книги: оглавление и издательский каталог.
#    Без этого в список «окказионализмов Лосева» попадали «метаполитика» и
#    «аристофаниана» — заглавия чужих книг из рекламного приложения.
# 4. Предварительный отсев OCR-мусора вынесен в отдельную функцию: токены с
#    латинскими буквами внутри кириллического слова, слова без гласных,
#    аномальные консонантные кластеры.
# 5. Кандидаты раскладываются по эвристическим корзинам — ручная верификация
#    перестаёт быть просмотром недифференцированного списка.
# 6. Порог доли гласных и длина консонантного кластера ослаблены: прежние
#    значения (0.15 без учёта длины; 5 согласных) отбраковывали нормативные
#    русские слова — «всплеск» (1 гласная на 7 букв) уходил в мусор.
#    Порог длины поднят с 9 до 12 букв как запас прочности. Проверка на
#    словах со стечением согласных («всплеснуть», «контрвзгляд»,
#    «встрепенувшись», «вздрогнувший») показала, что и при 9 буквах ложных
#    срабатываний не возникало: доля гласных у них 0,18–0,29, то есть выше
#    порога. Русского слова длиной 9+ букв с единственной гласной, судя по
#    проверке, не существует; запас взят на случай окказионализмов.
# 7. strip_backmatter учитывает маркер только во второй половине файла:
#    в «Тайном советнике» рекламный список изданий стоит на обороте титула,
#    и отсечение по минимальному индексу обрезало книгу на второй строке.
# 8. В выгрузке два пустых столбца для ручной разметки: решение верификатора
#    фиксируется в том же файле, отбор становится воспроизводимым.
# 9. Короткий OCR-мусор на кириллице (редакция 5.5). Прежняя версия выходила
#    на len(word) < 3 и пропускала в список кандидатов все двух- и
#    однобуквенные обрывки сканов «Эрмитажа». Существенно, куда вызывается
#    функция: токен доходит до неё, уже НЕ опознанный словарём OpenCorpora,
#    поэтому нормативные короткие слова («он», «их», «под») сюда не попадают,
#    а несловарный обрывок в 1–2 буквы — это инициал, номер сноски или брак
#    распознавания. Добавлены три признака: длина ≤ 2; «ь»/«ъ» в начале слова
#    (невозможно в русской орфографии); переход «строчная → заглавная» внутри
#    части слова («моСква»).
# 10. Пороги подобраны так, чтобы не задеть нормативный материал. Повтор буквы
#    отсекается с четырёх подряд, а не с трёх, иначе выпадает «длинношеее».
#    Регистровая проверка идёт по частям, разделённым дефисом, и требует
#    именно перехода «строчная → заглавная», иначе выпали бы
#    «Санкт-Петербург» (заглавная после дефиса) и «МХАТовский» (заглавная
#    после заглавной).
# 11. Отсев остаётся консервативным сознательно. Функция снимает только тот
#    мусор, который не может оказаться вкраплением; всё сомнительное идёт в
#    корзины и на ручной просмотр. Ошибка второго рода (лишний кандидат в
#    списке) стоит просмотра одной строки, ошибка первого рода (потерянное
#    вкрапление) не обнаруживается вовсе.
# 12. Мёртвый код удалён (ред. 5.6). После добавления в п. 9 проверки
#    `if len(low) <= 2: return True` нижележащая `if len(word) < 3: return
#    False` стала недостижимой: условия тождественны, до второй короткий
#    токен физически не доходит. Flake8/Ruff/Pylance выдавали предупреждение
#    о недостижимом коде.
# 13. Убраны неиспользуемые параметры: `line` в looks_like_ocr_noise и
#    `parse` в bucket. Ни один не читался в теле функции; оба остались от
#    ранних версий, где отсев зависел от строки, а корзина — от разбора.
# 14. Пути перестали быть абсолютными: аргумент командной строки →
#    LOSEV_CORPUS / LOSEV_OOV_OUTPUT → ./uploads, ./corpus, ./texts рядом
#    со скриптом → папка скрипта. Запуск:
#        python3 losev_oov.py [папка_с_текстами] [выходной_файл]
