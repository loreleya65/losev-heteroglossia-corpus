# -*- coding: utf-8 -*-
# РЕДАКЦИЯ 5.8 — 30.08.2026. Проверить экземпляр: python3 check_revision.py
"""
losev_oov.py — ПРОЦЕДУРА 2: поиск кириллических вкраплений методом
Out-of-Vocabulary (OOV).

Зачем отдельный файл
--------------------
В первой версии исследования латинские и кириллические вкрапления искались
«одним методом OOV через pymorphy3». Это терминологически неверно и было
справедливо отмечено рецензентом.

  pymorphy3 работает со словарём OpenCorpora, в котором содержатся ТОЛЬКО
  кириллические словоформы русского языка. Латинский токен парсер помечает
  граммемой LATN и не сверяет со словарём вовсе: для него это не «слово,
  отсутствующее в словаре», а вообще не объект морфологического анализа.

Поэтому:
  * латиница ищется регулярным выражением      → losev_extract.py
  * кириллица ищется методом OOV (pymorphy3)   → этот файл

Смешивать их под одной методологической шапкой нельзя.

Что делает скрипт
-----------------
1. Токенизирует кириллический текст.
2. Прогоняет каждую словоформу через pymorphy3.
3. Кандидатом в OOV считается словоформа, для которой ВСЕ разборы помечены
   как предположительные (parse.is_known == False).
4. Раскладывает кандидатов по эвристическим корзинам, чтобы облегчить
   ручную верификацию: OCR-мусор / имена собственные / «полу-» и «недо-» /
   филологические псевдотермины / прочее.
5. Пишет XLSX, где каждая словоформа снабжена контекстом и частотой.

ВАЖНО: выход скрипта — КАНДИДАТЫ, а не результат. Доля истинно иноязычных
среди них невелика; ручная верификация обязательна и является частью метода,
а не «доработкой напильником».

Установка:  pip install pymorphy3 pymorphy3-dicts-ru pandas openpyxl
Запуск:     python3 losev_oov.py
"""

from __future__ import annotations

import os
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import pandas as pd

try:
    import pymorphy3
except ImportError:                                     # pragma: no cover
    print("Нужен pymorphy3:  pip install pymorphy3 pymorphy3-dicts-ru",
          file=sys.stderr)
    raise

# ИСПРАВЛЕНИЕ (ред. 5.6): абсолютные пути /mnt/user-data/... заменены на
# разрешаемые по месту, иначе скрипт падает с FileNotFoundError у всякого, кто
# скачал архив и запустил его у себя. Порядок поиска — как в losev_extract.py.
BASE_DIR = Path(__file__).resolve().parent


def resolve_corpus_dir(argv: list[str] | None = None) -> Path:
    argv = argv if argv is not None else sys.argv[1:]
    if argv:
        return Path(argv[0]).expanduser().resolve()
    env = os.environ.get("LOSEV_CORPUS")
    if env:
        return Path(env).expanduser().resolve()
    for name in ("uploads", "corpus", "texts"):
        cand = BASE_DIR / name
        if cand.is_dir():
            return cand
    legacy = Path("/mnt/user-data/uploads")          # среда сборки материалов
    if legacy.is_dir():
        return legacy
    return BASE_DIR


def resolve_output_path(argv: list[str] | None = None) -> Path:
    argv = argv if argv is not None else sys.argv[1:]
    if len(argv) > 1:
        return Path(argv[1]).expanduser().resolve()
    env = os.environ.get("LOSEV_OOV_OUTPUT")
    if env:
        return Path(env).expanduser().resolve()
    legacy = Path("/mnt/user-data/outputs")
    if legacy.is_dir():
        return legacy / "losev_oov_candidates.xlsx"
    return BASE_DIR / "losev_oov_candidates.xlsx"


UPLOADS = resolve_corpus_dir()
OUTPUT = resolve_output_path()
OUTPUT.parent.mkdir(parents=True, exist_ok=True)

# Основной корпус = только два прижизненных эмигрантских сборника.
CORE_FILES = [("desant_1985*.txt", "Чудесный десант", 1985),
              ("tainii_sovetnik*.txt", "Тайный советник", 1987)]

RE_CYR_TOKEN = re.compile(r"[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*")
RE_LATIN = re.compile(r"[A-Za-z]")
RE_TOC_LEADER = re.compile(r"\.{6,}")

# Служебные зоны книги, которые не являются текстом Лосева.
# ИСПРАВЛЕНИЕ: в прежнем списке слов оказались «метаполитика» и
# «аристофаниана» — это заглавия книг И. Ефимова и В. Аксёнова из
# издательского каталога «Эрмитажа» в конце сборника 1985 г.
BACKMATTER_MARKERS = (
    "СОДЕРЖАНИЕ", "ОГЛАВЛЕНИЕ",
    "В ТОМ ЖЕ ИЗДАТЕЛЬСТВЕ", "КНИГИ ИЗДАТЕЛЬСТВА",
    "ДРУГИЕ КНИГИ ТОГО ЖЕ АВТОРА",
)

PREFIX_BUCKETS = [
    ("серия «полу-»",  re.compile(r"^полу[а-яё]{3,}")),
    ("серия «недо-»",  re.compile(r"^недо[а-яё]{3,}")),
    ("серия «пра-»",   re.compile(r"^(?:пра){2,}")),
]

PHILOLOGICAL_SUFFIXES = re.compile(
    r"[а-яё]+(?:ист|овед|олог|фил|иана|иада|изм)$"
)


def read_text(path: Path) -> str:
    for enc in ("utf-8", "utf-8-sig", "cp1251", "koi8-r"):
        try:
            return path.read_text(encoding=enc)
        except UnicodeDecodeError:
            continue
    return path.read_text(encoding="utf-8", errors="replace")


def strip_backmatter(text: str) -> str:
    """Отрезает оглавление и издательский каталог.

    ИСПРАВЛЕНИЕ: маркер учитывается только во ВТОРОЙ половине книги.
    В «Тайном советнике» рекламный список изданий «Эрмитажа» стоит на
    обороте титула, то есть В НАЧАЛЕ; отсечение по минимальному индексу
    маркера обрезало файл на второй строке и обнуляло весь разбор книги.
    """
    lines = text.splitlines()
    floor = len(lines) // 2
    cut = len(lines)
    for i, ln in enumerate(lines):
        if i < floor:
            continue
        s = ln.strip().upper()
        if any(s.startswith(m) for m in BACKMATTER_MARKERS):
            cut = min(cut, i)
    return "\n".join(l for l in lines[:cut] if not RE_TOC_LEADER.search(l))


def looks_like_ocr_noise(word: str) -> bool:
    """Кириллический токен, испорченный распознаванием."""
    if RE_LATIN.search(word):
        return True

    low = word.lower()

    # ИСПРАВЛЕНИЕ (ред. 5.5). Прежняя версия выходила на len(word) < 3, то есть
    # пропускала весь короткий мусор сканов «Эрмитажа» в список кандидатов.
    # Важно помнить, куда эта функция вызывается: до неё токен уже НЕ опознан
    # словарём OpenCorpora. Нормативные короткие слова («он», «их», «под»)
    # словарны и сюда не доходят. Несловарный кириллический обрывок длиной
    # 1–2 буквы — это инициал, номер сноски или брак распознавания; ни один из
    # трёх случаев не является вкраплением.
    if len(low) <= 2:
        return True

    # Мягкий и твёрдый знак в начале слова невозможны в русской орфографии.
    if low[0] in "ьъ":
        return True

    # Одна буква, повторённая четыре и более раз подряд («нннн»), — след
    # растянутого или пропечатанного насквозь набора. Порог именно 4, а не 3:
    # при 3 под фильтр попадает нормативное «длинношеее».
    if re.search(r"(.)\1{3,}", low):
        return True

    # Заглавная буква ПОСЛЕ строчной внутри одной части слова («бВет»,
    # «моСква») — след разнокегельного набора, а не словообразования.
    # Проверка идёт по частям, разделённым дефисом, и требует именно перехода
    # «строчная → заглавная»: иначе под фильтр попали бы «Санкт-Петербург»
    # (заглавная после дефиса) и «МХАТовский» (заглавная после заглавной).
    if any(re.search(r"[а-яё][А-ЯЁ]", part) for part in word.split("-")):
        return True

    vowels = sum(1 for c in low if c in "аеёиоуыэюя")
    if vowels == 0:
        return True
    # ИСПРАВЛЕНИЕ: прежний порог 0.15 без учёта длины отбраковывал нормальные
    # русские слова с одной гласной: «всплеск» даёт 1/7 = 0.143 и попадал в
    # мусор. Порог снижен и применяется только к длинным словам.
    if len(word) >= 12 and vowels / len(word) < 0.12:
        return True
    # ИСПРАВЛЕНИЕ: кластер поднят с 5 до 6 согласных. При пяти под фильтр
    # попадали нормативные слова со стечением согласных.
    if re.search(r"[бвгджзйкпстфхцчшщ]{6,}", low):
        return True
    return False


def bucket(word: str) -> str:
    low = word.lower()
    for name, rx in PREFIX_BUCKETS:
        if rx.match(low):
            return name
    if word[0].isupper():
        return "предположительно оним"
    if PHILOLOGICAL_SUFFIXES.match(low):
        return "филологический псевдотермин"
    if "-" in word:
        return "сложение через дефис"
    if len(low) > 13:
        return "сложение / контаминация"
    return "прочее (проверить вручную)"


def main():
    morph = pymorphy3.MorphAnalyzer()
    rows = []
    freq: Counter = Counter()
    context: dict[str, tuple[str, str]] = {}
    per_book: defaultdict[str, Counter] = defaultdict(Counter)
    total_tokens = 0

    for pattern, title, year in CORE_FILES:
        hits = sorted(UPLOADS.glob(pattern))
        if not hits:
            print(f"  ! не найден файл по шаблону {pattern}", file=sys.stderr)
            continue
        text = strip_backmatter(read_text(hits[0]))

        for line in text.splitlines():
            for m in RE_CYR_TOKEN.finditer(line):
                word = m.group()
                total_tokens += 1
                if looks_like_ocr_noise(word):
                    continue
                parses = morph.parse(word)
                if parses and any(p.is_known for p in parses):
                    continue                       # словарное слово — не OOV
                key = word.lower()
                freq[key] += 1
                per_book[key][title] += 1
                context.setdefault(key, (word, line.strip()[:220]))

    for key, n in freq.most_common():
        surface, ctx = context[key]
        rows.append({
            "Словоформа": surface,
            "Частота в корпусе": n,
            "Книги": ", ".join(f"{b} ({c})" for b, c in per_book[key].items()),
            "Эвристическая корзина": bucket(surface),
            "Контекст": ctx,
            "Верификация (заполняется вручную)": "",
            "Категория после верификации": "",
        })

    df = pd.DataFrame(rows)
    with pd.ExcelWriter(OUTPUT, engine="openpyxl") as xw:
        df.to_excel(xw, sheet_name="OOV-кандидаты", index=False)
        pd.DataFrame([{
            "Словоупотреблений (кириллица)": total_tokens,
            "Уникальных OOV-кандидатов": len(df),
            "Доля OOV от корпуса, %": round(df["Частота в корпусе"].sum()
                                            / max(total_tokens, 1) * 100, 2),
        }]).to_excel(xw, sheet_name="Сводка", index=False)
        xw.sheets["OOV-кандидаты"].freeze_panes = "A2"

    print(f"Словоупотреблений: {total_tokens}")
    print(f"OOV-кандидатов (уникальных): {len(df)}")
    print(f"Готово → {OUTPUT}")
    return df


if __name__ == "__main__":
    main()

